#!/usr/bin/env python3
"""
Builds Data/ItemNames.lua (item name -> item ID) from Questie's Forever item
database (QuestieDB, https://github.com/Questie/Questie, GPLv3).

Recipe tooltips and trainers name their items and reagents without links,
and the game only knows the names of items it has loaded. With this list
Gathercraft can turn "Strange Dust" into item 10940 right away.

Usage:
    python import_item_names.py <QuestieDB>/data/Forever -o ../Data/ItemNames.lua
"""
import argparse, os, re, sys

ROW = re.compile(r"^\[(\d+)\] = \{'((?:[^'\\]|\\.)*)'", re.M)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("forever_dir", help="QuestieDB/data/Forever")
    ap.add_argument("-o", "--out", default="ItemNames.lua")
    args = ap.parse_args()
    text = open(os.path.join(args.forever_dir, "foreverItemDB.lua"), encoding="utf-8").read()
    body = text[text.index("QuestieDB.itemData"):]
    names = {}
    for item_id, name in ROW.findall(body):
        name = name.replace("\\'", "'").replace("\\\\", "\\")
        if not name or "\n" in name or "|" in name or "\t" in name:
            continue
        item_id = int(item_id)
        key = name.lower()
        # same name twice (old copies, faction versions): keep the lowest ID
        if key not in names or item_id < names[key][0]:
            names[key] = (item_id, name)
    lines = [
        "-- Generated by tools/import_item_names.py, do not edit by hand.",
        "-- Item names from Questie (https://github.com/Questie/Questie), licensed under the GPLv3.",
        "-- One item per line: ID<tab>name. Read only when a recipe needs a name.",
        "GathercraftItemNames = [==[",
    ]
    for item_id, name in sorted(names.values()):
        lines.append("%d\t%s" % (item_id, name))
    lines += ["]==]", ""]
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %d item names -> %s" % (len(names), args.out), file=sys.stderr)


if __name__ == "__main__":
    main()
