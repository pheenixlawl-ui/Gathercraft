#!/usr/bin/env python3
"""
Builds Data/NodeNames.lua: the names of every herb, ore and chest object of
Data/QuestieNodes.lua in the other client languages, from Questie's object
lookups (QuestieDB/l10n/Forever/lookupObjects, GPLv3).

Usage:
    python import_node_names.py <QuestieDB>/l10n/Forever/lookupObjects -o ../Data/NodeNames.lua
"""
import argparse, os, re, sys

LOCALES = ["deDE", "esES", "esMX", "frFR", "koKR", "ptBR", "ruRU", "zhCN", "zhTW"]
ROW = re.compile(r'^\[(\d+)\]\s*=\s*"((?:[^"\\]|\\.)*)"', re.M)


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("lookup_dir")
    ap.add_argument("-o", "--out", default="NodeNames.lua")
    ap.add_argument("--nodes", default=os.path.join(os.path.dirname(__file__), "..", "Data", "QuestieNodes.lua"))
    args = ap.parse_args()
    ids = sorted({int(i) for i in re.findall(r'\["o(\d+)"\]\s*=\s*\{', open(args.nodes, encoding="utf-8").read())})
    lines = [
        "-- Generated by tools/import_node_names.py, do not edit by hand.",
        "-- Herb, ore and chest names in other client languages, from Questie",
        "-- (https://github.com/Questie/Questie), licensed under the GPLv3.",
        "GathercraftNodeNames = {",
    ]
    total = 0
    for loc in LOCALES:
        path = os.path.join(args.lookup_dir, loc + ".lua")
        if not os.path.exists(path):
            continue
        names = {int(i): n.replace('\\"', '"').replace("\\\\", "\\") for i, n in ROW.findall(open(path, encoding="utf-8").read())}
        parts = ["[%d]=%s" % (i, lua_str(names[i])) for i in ids if names.get(i)]
        total += len(parts)
        lines.append("    %s = { %s }," % (loc, ", ".join(parts)))
    lines += ["}", ""]
    open(args.out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    print("wrote %d names for %d objects -> %s" % (total, len(ids), args.out), file=sys.stderr)


if __name__ == "__main__":
    main()
