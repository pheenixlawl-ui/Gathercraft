#!/usr/bin/env python3
"""
Builds Data/AreaMaps.lua: zone area IDs (as Questie stores NPC positions) ->
map IDs of the game's map (UiMapID), so Gathercraft can set a waypoint to a
recipe vendor.

    python tools/import_area_maps.py <QuestieDB>/data/Forever -o Data/AreaMaps.lua

Source: QuestieDB (https://github.com/Questie/Questie), GPLv3 - credited in NOTICE.md.
"""
import argparse, json, os

ap = argparse.ArgumentParser()
ap.add_argument("forever_dir", help="QuestieDB/data/Forever")
ap.add_argument("-o", "--out", default="AreaMaps.lua")
args = ap.parse_args()
conv = json.load(open(os.path.join(args.forever_dir, "conversion.json"), encoding="utf-8"))
pairs = sorted({(t["area_id"], t["ui_map_id"]) for t in conv["geometry"]["transforms"]})
with open(args.out, "w", encoding="utf-8", newline="\n") as f:
    f.write("-- Generated by tools/import_area_maps.py, do not edit by hand.\n")
    f.write("-- Zone area IDs -> map IDs, from the Questie database\n")
    f.write("-- (https://github.com/Questie/Questie, GPLv3).\n")
    f.write("GathercraftAreaMaps = {\n")
    for area, ui in pairs:
        f.write("    [%d] = %d,\n" % (area, ui))
    f.write("}\n")
print("%d zones -> %s" % (len(pairs), args.out))
